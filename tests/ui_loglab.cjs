const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const os = require('node:os');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({headless:true, channel:'msedge'});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:8766/static/labs/logs/index.html');
    await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('10.000'));
    assert.equal(await page.locator('#rows tr').count(),40);
    await page.locator('#profile').fill('UI test'); await page.locator('#load-draft').click();
    await page.locator('[data-tab="scan"]').click();
    assert.equal(await page.locator('#source-notes textarea').count(),29);
    assert.equal(await page.locator('#day-notes textarea').count(),10);
    await page.getByRole('textbox',{name:'Nhận xét iam',exact:true}).fill('Tìm policy_change toàn nguồn, xem EVT000315.');
    await page.locator('#source').selectOption('iam');
    await page.locator('#day').selectOption('2026-10-20');
    await page.locator('#query').fill('EVT000315');
    await page.waitForFunction(()=>document.querySelector('#rows').textContent.includes('EVT000315'));
    await page.getByRole('button',{name:'EVT000315',exact:true}).click();
    assert.match(await page.locator('#json').innerText(),/mfa_required/);
    await page.locator('#pin').click();
    await page.getByRole('button',{name:'actor_id: nv_it_01',exact:true}).click();
    assert.equal(await page.locator('#source').inputValue(),'');
    assert.equal(await page.locator('#day').inputValue(),'');
    assert.equal(await page.locator('#query').inputValue(),'nv_it_01');
    await page.locator('#reset').click(); await page.locator('#query').fill('EVT002280');
    await page.waitForFunction(()=>document.querySelector('#rows').textContent.includes('EVT002280'));
    await page.getByRole('button',{name:'EVT002280',exact:true}).click(); await page.locator('#pin').click(); await page.locator('#close').click();
    await page.locator('[data-tab="handover"]').click();
    assert.match(await page.locator('#evidence').innerText(),/2 event · 2 nguồn · 2 ngày/);
    await page.locator('[data-note="ban_giao"]').fill('Cần xác minh ngoại lệ MFA và bảo toàn log.');
    const report = await page.evaluate(()=>window.eval('report()'));
    assert.match(report,/EVT000315/); assert.match(report,/EVT002280/); assert.match(report,/Tìm policy_change/);
    await page.reload(); await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('10.000'));
    await page.locator('#profile').fill('UI test'); await page.locator('#load-draft').click();
    await page.locator('[data-tab="handover"]').click();
    assert.match(await page.locator('[data-note="ban_giao"]').inputValue(),/ngoại lệ MFA/);
    assert.equal(await page.locator('#evidence .evidence-row').count(),2);
    await page.screenshot({path:path.join(os.tmpdir(),'codex-loglab-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.locator('[data-tab="map"]').click();
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:path.join(os.tmpdir(),'codex-loglab-mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]); console.log('PASS: full dataset, filters, global pivot, pin/timeline, drafts, report, mobile; no browser errors.');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1);});
