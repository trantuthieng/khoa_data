// Chạy với server cục bộ cổng 8765, không dùng lớp học thật.
const { chromium } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const out = path.resolve(__dirname, '../design/previews');
  await fs.mkdir(out, { recursive: true });
  const errors = [];
  const track = p => p.on('pageerror', e => errors.push(e.message));
  const checkWidth = async p => assert.ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Trang bị tràn ngang');
  try {
    const home = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
    track(home);
    await home.goto('http://127.0.0.1:8765/');
    await home.getByRole('heading', { name: 'Vào lớp học', exact: true }).waitFor();
    await checkWidth(home);
    await home.screenshot({ path: path.join(out,'01-vao-lop.png'), fullPage: true });
    await home.setViewportSize({ width: 390, height: 844 });
    await checkWidth(home);
    await home.screenshot({ path: path.join(out,'05-dien-thoai.png'), fullPage: true });
    const teacher = await browser.newPage({ viewport: { width: 1600, height: 1000 }, colorScheme: 'light' });
    track(teacher);
    await teacher.goto('http://127.0.0.1:8765/teacher');
    await teacher.locator('#pw').fill('test-teacher-only');
    await teacher.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
    await teacher.waitForFunction(() => document.querySelector('#app').__vue_app__._container._vnode.component.proxy.authed === true);
    const session = await teacher.evaluate(async () => {
      const vm = document.querySelector('#app').__vue_app__._container._vnode.component.proxy;
      const c = await api('POST','/api/t/classes',{name:'Lớp minh họa · An toàn dữ liệu'});
      await api('PATCH',`/api/t/classes/${c.id}`,{active_module:6});
      const students = [];
      for (let i=1;i<=8;i++) students.push(await api('POST','/api/join',{code:c.code,name:'Học viên mẫu '+i}));
      const aid = 'm06-sql01-v1';
      await api('POST',`/api/t/classes/${c.id}/activities/${aid}`,{status:'open'});
      for (const st of students.slice(0,6)) await api('POST','/api/s/activity/'+aid,{payload:{fields:{code:'SELECT region, kwh FROM customers ORDER BY id;',result:'6 dòng, hai cột region và kwh.',explain:'Chỉ lấy các cột cần dùng trong bản xuất.',run_state:[{state:'Đã chạy / đã thao tác'}]}}},st.token);
      const res = await api('GET',`/api/t/classes/${c.id}/activities/${aid}/results`);
      for (const [i,r] of res.responses.slice(0,4).entries()) await api('POST',`/api/t/classes/${c.id}/responses/${r.id}/grade`,{version:r.version,score:8+i*.25,max_score:10,feedback:'Chọn đúng cột. Nêu rõ thêm mục đích và phạm vi bản xuất.'});
      await vm.enterClass({...c,active_module:6});
      const sec = vm.mod.sections.find(s=>s.activity===aid);
      await vm.presentSection(sec.id);
      return {...students[0],cls:c.code};
    });
    await teacher.getByRole('heading',{name:'Điều khiển lớp học',exact:true}).waitFor();
    await checkWidth(teacher);
    await teacher.screenshot({path:path.join(out,'03-dieu-khien-lop.png'),fullPage:true});
    await teacher.evaluate(()=>document.querySelector('#app').__vue_app__._container._vnode.component.proxy.openResults('m06-sql01-v1'));
    await teacher.getByText('Theo dõi và chấm bài cá nhân',{exact:true}).waitFor();
    await teacher.evaluate(()=>window.scrollTo(0,0));
    await teacher.screenshot({path:path.join(out,'04-cham-bai.png'),fullPage:false});
    const learner = await browser.newPage({viewport:{width:1440,height:1000},colorScheme:'light'});
    track(learner);
    await learner.goto('http://127.0.0.1:8765/');
    await learner.evaluate(s=>localStorage.setItem('session',JSON.stringify(s)),session);
    await learner.goto('http://127.0.0.1:8765/learn');
    await learner.waitForFunction(()=>document.querySelector('#app').__vue_app__._container._vnode.component.proxy.state!==null);
    await learner.evaluate(()=>document.querySelector('#app').__vue_app__._container._vnode.component.proxy.openActivity('m06-sql01-v1'));
    await learner.getByText('SELECT ___, ___ FROM customers ORDER BY id;',{exact:true}).waitFor();
    await learner.evaluate(()=>window.scrollTo(0,0));
    await checkWidth(learner);
    await learner.screenshot({path:path.join(out,'02-hoc-vien.png'),fullPage:true});
    await learner.setViewportSize({width:390,height:844});
    await checkWidth(learner);
    await learner.getByRole('button',{name:'Mục lục',exact:true}).click();
    await learner.getByRole('button',{name:'Đóng mục lục',exact:true}).waitFor();
    await learner.getByRole('button',{name:'Đóng mục lục',exact:true}).click();
    await learner.evaluate(()=>window.scrollTo(0,0));
    await learner.screenshot({path:path.join(out,'06-bai-tap-dien-thoai.png'),fullPage:true});
    await teacher.setViewportSize({width:390,height:844});
    await checkWidth(teacher);
    await teacher.getByRole('button',{name:'Hoạt động',exact:true}).click();
    await teacher.getByRole('button',{name:'Đóng hoạt động',exact:true}).waitFor();
    await teacher.getByRole('button',{name:'Đóng hoạt động',exact:true}).click();
    await teacher.getByRole('button',{name:'Mục lục',exact:true}).click();
    await teacher.getByRole('button',{name:'Đóng mục lục',exact:true}).click();
    await learner.emulateMedia({colorScheme:'dark'});
    await learner.waitForTimeout(250);
    await learner.screenshot({path:path.join(out,'07-che-do-toi.png'),fullPage:false});
    assert.deepEqual(errors,[]);
    console.log('PASS: desktop and mobile layouts, both teacher drawers, learner navigation, dark mode, no horizontal overflow or JavaScript errors. Previews: '+out);
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
